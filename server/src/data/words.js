export function isFourLetterWord(word) {
  if (!word || typeof word !== 'string') return false;
  const cleanWord = word.trim().toUpperCase();
  if (cleanWord.length !== 4) return false;
  if (!/^[A-Z]{4}$/.test(cleanWord)) return false;
  return FOUR_LETTER_WORDS.has(cleanWord);
}
